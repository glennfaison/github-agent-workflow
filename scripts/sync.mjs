#!/usr/bin/env node
// Regenerates the files that are derived from the skills, so nobody edits them by hand:
//
//   .claude-plugin/plugin.json                         the "skills" list (every promoted skill on disk)
//   skills/meta/runner-prompts/references/prompts.md   one prompt block per pipeline skill, built from
//                                                      that skill's `## Inputs` table
//
//   node scripts/sync.mjs           write the files
//   node scripts/sync.mjs --check   change nothing; exit 1 if a file is out of date (CI runs this)
//
// The Inputs tables stay canonical (see AGENTS.md). A change to an input is one edit, followed by
// `npm run sync`.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const NOT_PROMOTED = new Set(["deprecated", "in-progress"]);
const dirs = (p) => (existsSync(p) ? readdirSync(p).filter((n) => statSync(join(p, n)).isDirectory()) : []);
const read = (p) => readFileSync(join(root, p), "utf8");

// ---- skills on disk ---------------------------------------------------------------------------
const promoted = [];
for (const bucket of dirs(join(root, "skills")).sort()) {
  if (NOT_PROMOTED.has(bucket)) continue;
  for (const name of dirs(join(root, "skills", bucket)).sort()) promoted.push({ bucket, name, rel: `skills/${bucket}/${name}` });
}

// ---- the pipeline, in order: each step has a group skill and an item skill ---------------------
const STEPS = [
  { step: "Exploring", group: "explore-github-repo", item: "file-github-issues", itemTarget: null },
  { step: "Triaging", group: "triage-github-issues", item: "triage-github-issue", itemTarget: "123" },
  { step: "Implementing", group: "implement-github-issues", item: "implement-github-issue", itemTarget: "123" },
  { step: "Shepherding", group: "shepherd-github-prs", item: "shepherd-github-pr", itemTarget: "124" },
  { step: "Reviewing", group: "review-github-prs", item: "review-github-pr", itemTarget: "124" },
];
const NOTES = {
  "file-github-issues":
    "One candidate as key-value pairs: fill in each empty `title` to `evidence` line. For several candidates, list them as free text instead.",
};

/** The rows of a skill's `## Inputs` table, as { key, def } where def is the value a prompt should show. */
function inputs(skill) {
  const body = read(`skills/pipeline/${skill}/SKILL.md`).replace(/^---\n[\s\S]*?\n---\n?/, "");
  const lines = body.split("\n");
  const start = lines.findIndex((l) => /^## Inputs(\s|$)/.test(l));
  if (start === -1) throw new Error(`${skill}: no ## Inputs section`);
  const rows = [];
  for (const l of lines.slice(start + 1)) {
    if (/^## /.test(l)) break;
    const m = l.match(/^\|\s*`([a-z][a-z0-9_]*)`\s*\|\s*(.*?)\s*\|/);
    if (!m) continue;
    const [, key, cell] = m;
    if (cell.startsWith("*(required)*") || cell.startsWith("*(from free text)*")) continue; // the target, or free text
    let def;
    if (cell.startsWith("*(")) def = ""; // *(none)* and *(per candidate)*
    else def = cell.match(/`([^`]*)`/)?.[1] ?? "";
    rows.push({ key, def: key === "runner" ? "NAME" : def });
  }
  return rows;
}

function promptsMd() {
  const covered = new Set(STEPS.flatMap((s) => [s.group, s.item]));
  for (const s of promoted.filter((x) => x.bucket === "pipeline")) {
    if (!covered.has(s.name)) throw new Error(`scripts/sync.mjs: pipeline skill ${s.name} is not in STEPS`);
  }
  const out = [
    "<!-- Generated by `npm run sync` from each skill's `## Inputs` table. Do not edit by hand. -->",
    "",
    "# Runner prompts",
    "",
    "Paste a block into a scheduler, webhook or chat. Replace `OWNER/REPO`, `NAME`, and the issue or PR number. Every input the skill accepts is listed with its default as the value; an empty value means no default. Delete a line to leave that input at its default.",
    "",
    "If `/skill-name` is not recognised by your runner, call the Skill tool with that skill name instead.",
    "",
  ];
  for (const s of STEPS) {
    out.push(`## ${s.step}`, "");
    for (const [kind, name, target] of [["Group skill, run on a schedule", s.group, null], ["Item skill, run by hand", s.item, s.itemTarget]]) {
      const rows = inputs(name);
      const head = kind.startsWith("Group") ? `Run /${name} on github.com/OWNER/REPO` : target ? `Run /${name} ${target}` : `Run /${name}`;
      out.push(`### ${kind}: \`${name}\``, "");
      if (NOTES[name]) out.push(NOTES[name], "");
      out.push("```", head, ...rows.map((r) => `${r.key}=${r.def}`), "```", "");
    }
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

function pluginJson() {
  const plugin = JSON.parse(read(".claude-plugin/plugin.json"));
  plugin.skills = promoted.map((s) => `./${s.rel}`);
  return JSON.stringify(plugin, null, 2) + "\n";
}

const targets = [
  [".claude-plugin/plugin.json", pluginJson],
  ["skills/meta/runner-prompts/references/prompts.md", promptsMd],
];
let stale = 0;
for (const [file, make] of targets) {
  const want = make();
  const path = join(root, file);
  const have = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (have === want) continue;
  if (check) {
    console.error(`${file} is out of date. Run \`npm run sync\`.`);
    stale += 1;
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${file}`);
  }
}
if (check && stale) process.exit(1);
if (!stale) console.log(check ? "generated files are up to date" : "done");
